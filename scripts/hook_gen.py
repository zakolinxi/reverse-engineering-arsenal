PRELUDE = r"""
/* Generated by reverse-engineering-arsenal/scripts/hook_gen.py
 * Paste before the target logic runs (document-start / CDP preload / ruyipage preload).
 * Inspect: window.__REA_STATE__.logs ; console lines start with [REA].
 * Authorized testing only. Hooks are observable by anti-debug code; prefer engine-level
 * tracing (RuyiTrace / Firefox-Reverse) when stealth matters.
 */
(() => {
  if (window.__REA_STATE__ && window.__REA_STATE__.installed) {
    console.warn('[REA] hooks already installed');
    return;
  }
  const MAX_BODY = __MAX_BODY__;
  const MAX_LOGS = 5000;
  const state = window.__REA_STATE__ = { installed: true, logs: [] };
  const truncate = (value, limit) => {
    if (typeof value !== 'string') return value;
    return value.length > limit ? value.slice(0, limit) + `...<truncated ${value.length - limit} chars>` : value;
  };
  const describe = (value) => {
    try {
      if (value === null || value === undefined) return String(value);
      if (typeof value === 'string') return truncate(value, MAX_BODY);
      if (typeof value === 'function') return `[Function ${value.name || 'anonymous'}]`;
      if (value instanceof ArrayBuffer) return `[ArrayBuffer ${value.byteLength}]`;
      if (ArrayBuffer.isView(value)) {
        const bytes = new Uint8Array(value.buffer, value.byteOffset, Math.min(value.byteLength, 256));
        return `[${value.constructor.name} ${value.byteLength}] ` + Array.from(bytes, b => b.toString(16).padStart(2, '0')).join('');
      }
      if (value instanceof Error) return `${value.name}: ${value.message}`;
      return truncate(JSON.stringify(value), MAX_BODY);
    } catch (error) {
      try { return String(value); } catch (_) { return '[unserializable]'; }
    }
  };
  const push = (type, data) => {
    const entry = { t: Date.now(), type, data };
    state.logs.push(entry);
    if (state.logs.length > MAX_LOGS) state.logs.shift();
    try { console.log('[REA]', type, data); } catch (_) {}
  };
  const argsOf = (args) => Array.from(args || [], describe);
  state.push = push;
  state.describe = describe;
  state.argsOf = argsOf;
})();
"""

