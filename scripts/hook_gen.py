TYPE_ALIASES = {
    "all": ["fetch", "xhr", "websocket", "cookie", "storage", "crypto", "json", "eval", "timer"],
    "network": ["fetch", "xhr", "websocket"],
}


def js_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build(kind: str, target: str | None, prop: str | None, max_body: int) -> str:
    kinds = TYPE_ALIASES.get(kind, [kind])
    if kind not in SNIPPETS and kind not in TYPE_ALIASES:
        raise SystemExit(f"unknown hook type: {kind}")
    parts = [PRELUDE.replace("__MAX_BODY__", str(max_body))]
    for item in kinds:
        snippet = SNIPPETS[item]
        if item == "function":
            if not target:
                raise SystemExit("--target is required for --type function")
            snippet = snippet.replace("__TARGET__", js_string(target))
        if item == "property":
            if not prop:
                raise SystemExit("--property is required for --type property")
            snippet = snippet.replace("__PROPERTY__", js_string(prop))
        parts.append(snippet.strip())
    return "\n\n".join(parts) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate JS hooks for authorized reverse engineering.")
    parser.add_argument("--type", default="all",
                        help="fetch|xhr|websocket|cookie|storage|crypto|json|eval|timer|function|property|network|all")
    parser.add_argument("--target", help="global function name for --type function")
    parser.add_argument("--property", help="property path for --type property, e.g. navigator.userAgent")
    parser.add_argument("--max-body", type=int, default=4096, help="maximum logged string/body length")
    parser.add_argument("--out", help="write hook to a file instead of stdout")
    parser.add_argument("--list", action="store_true", help="list available hook types")
    args = parser.parse_args()

    if args.list:
        print("types:", ", ".join(list(SNIPPETS) + ["network", "all"]))
        return 0
    output = build(args.type, args.target, args.property, args.max_body)
    if args.out:
        with open(args.out, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(output)
        print(f"wrote {args.out} ({len(output)} bytes)")
    else:
        sys.stdout.write(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
