#!/usr/bin/env python3
"""Generate JavaScript runtime hooks for authorized reverse-engineering sessions.

Hooks log to window.__REA_STATE__.logs and console under the [REA] prefix.
Paste the output into DevTools, a CDP addScriptToEvaluateOnNewDocument call, or a
ruyipage add_preload_script (wrap the snippet in a function string).

Examples:
  python hook_gen.py --type fetch --out fetch_hook.js
  python hook_gen.py --type all
  python hook_gen.py --type function --target encrypt
  python hook_gen.py --type property --property navigator.userAgent
"""

from __future__ import annotations

